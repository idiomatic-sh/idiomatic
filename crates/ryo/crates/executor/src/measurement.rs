pub struct Measurement {
    pub sessions: usize,
    pub rounds: Vec<usize>,
    pub empty_reader_epochs: usize,
    pub bulk_screen_files: usize,
    pub old_route: std::collections::BTreeMap<String, usize>,
    pub project_counts: [usize; 4],
    pub calls: usize,
    pub requests: usize,
    pub refused: usize,
    pub reasons: BTreeMap<String, usize>,
    pub worker_cpu: f64,
    pub file_shards: usize,
    pub dispatch_wall: [f64; 5],
    pub largest_file: String,
    pub parallel_rows: usize,
    pub delivery_dictionaries: usize,
    pub empty_file_epochs: usize,
    pub omitted_file_bindings: usize,
    pub admission_shards: usize,
    pub project_shards: usize,
    pub project_prepare_wall: f64,
    pub project_provider_wall: f64,
    pub project_number_wall: f64,
    pub project_numbered: usize,
    pub empty_project_epochs: usize,
    pub call_wall: f64,
    pub phase_wall: [f64; 4],
    pub parts: [f64; 6],
    pub bound_proofs: f64,
    pub literal_positions: usize,
    pub witnesses: [usize; 4],
    pub named_counts: [usize; 4],
    pub exact_inputs: [usize; 8],
    pub named_cpu: f64,
    pub certified: usize,
    pub empty: usize,
    pub requirement_programs: usize,
    pub requirement_bindings: usize,
    pub counts: [usize; 10],
    pub reused_binding_entries: usize,
    pub pattern_visits: [usize; 4],
    pub registration: [usize; 10],
    pub overlay: [usize; 2],
}
